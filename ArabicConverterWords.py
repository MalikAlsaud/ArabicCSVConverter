def reshape_arabic_text(text):
    """Reshape Arabic text and convert specific characters"""
    if not text:
        return ""
    
    # Reshape the text
    reshaped = arabic_reshaper.reshape(text)
    letters = list(reshaped)
    word_list = []
    
    for letter in letters:
        if ord(letter) in lettersList:
            letter = chr(lettersList[ord(letter)])
            word_list.append(letter)
        else:
            word_list.append(letter)
    
    return ''.join(word_list)

# Expose the function to JavaScript
window.reshapeArabicText = reshape_arabic_text